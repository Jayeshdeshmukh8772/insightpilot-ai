def _add_background(canvas_obj, doc):
    """Add dark background to every page."""
    canvas_obj.saveState()
    canvas_obj.setFillColor(DARK_BG)
    canvas_obj.rect(0, 0, A4[0], A4[1], fill=True, stroke=False)
    
    # Accent bar on left edge
    canvas_obj.setFillColor(INDIGO)
    canvas_obj.rect(0, 0, 4, A4[1], fill=True, stroke=False)
    
    # Header line
    canvas_obj.setStrokeColor(SURFACE)
    canvas_obj.setLineWidth(0.5)
    canvas_obj.line(20 * mm, A4[1] - 12 * mm, A4[0] - 20 * mm, A4[1] - 12 * mm)
    
    # Page number
    page_num = canvas_obj.getPageNumber()
    canvas_obj.setFillColor(TEXT_SECONDARY)
    canvas_obj.setFont("Helvetica", 8)
    canvas_obj.drawCentredString(A4[0] / 2, 8 * mm, f"InsightPilot AI  ·  Page {page_num}")
    
    canvas_obj.restoreState()


