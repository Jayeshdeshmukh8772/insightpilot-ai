def generate_pdf_report(
    profile: Dict[str, Any],
    qa_history: List[Dict],
    chart_images: List[bytes],
    executive_summary: str,
) -> bytes:
    """Generate a complete PDF report and return as bytes."""
    
    buffer = io.BytesIO()
    
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=20 * mm,
        leftMargin=20 * mm,
        topMargin=15 * mm,
        bottomMargin=15 * mm,
    )
    
    styles = _build_styles()
    story = []
    
    # Cover Page
    story.extend(_cover_page(profile, styles))
    story.append(PageBreak())
    
    # Dataset Overview
    story.extend(_dataset_overview_section(profile, styles))
    story.append(Spacer(1, 12))
    
    # Executive Summary
    story.extend(_executive_summary_section(executive_summary, styles))
    story.append(PageBreak())
    
    # Analysis Results
    story.extend(_analysis_section(qa_history, chart_images, styles))
    
    # Footer note
    story.append(Spacer(1, 20))
    story.append(Paragraph(
        f"Generated by InsightPilot AI • {datetime.now().strftime('%B %d, %Y at %I:%M %p')}",
        styles["footer"]
    ))
    
    doc.build(story, onFirstPage=_add_background, onLaterPages=_add_background)
    
    return buffer.getvalue()


