def _dataset_overview_section(profile: Dict, styles: Dict) -> list:
    """Dataset overview with column breakdown."""
    story = []
    story.append(Paragraph("Dataset Overview", styles["section_header"]))
    story.append(HRFlowable(width="100%", thickness=0.5, color=SURFACE2, spaceAfter=8))
    
    # Column type breakdown
    col_profiles = profile.get("column_profiles", [])
    if col_profiles:
        story.append(Paragraph("Column Summary", styles["subsection"]))
        
        table_data = [["Column", "Type", "Missing", "Unique Values"]]
        for cp in col_profiles[:20]:  # Limit to first 20
            table_data.append([
                cp.get("name", ""),
                cp.get("type", ""),
                f"{cp.get('null_pct', 0):.1f}%",
                f"{cp.get('unique_count', 0):,}",
            ])
        
        col_table = Table(table_data, colWidths=[2.5 * inch, 1 * inch, 1 * inch, 1.2 * inch])
        col_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), SURFACE2),
            ("TEXTCOLOR", (0, 0), (-1, 0), CYAN),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, 0), 9),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [SURFACE, DARK_BG]),
            ("TEXTCOLOR", (0, 1), (-1, -1), TEXT_PRIMARY),
            ("FONTSIZE", (0, 1), (-1, -1), 9),
            ("PADDING", (0, 0), (-1, -1), 6),
            ("GRID", (0, 0), (-1, -1), 0.3, SURFACE2),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))
        story.append(col_table)
    
    return story


def _executive_summary_section(summary: str, styles: Dict) -> list:
    """Executive summary section."""
    story = []
    story.append(Paragraph("Executive Summary", styles["section_header"]))
    story.append(HRFlowable(width="100%", thickness=0.5, color=SURFACE2, spaceAfter=8))
    
    if summary:
        for para in summary.split("\n\n"):
            if para.strip():
                story.append(Paragraph(para.strip(), styles["body"]))
                story.append(Spacer(1, 6))
    
    return story


def _analysis_section(qa_history: List[Dict], chart_images: List[bytes], styles: Dict) -> list:
    """Analysis Q&A with charts and insights."""
    story = []
    story.append(Paragraph("Analysis Results", styles["section_header"]))
    story.append(HRFlowable(width="100%", thickness=0.5, color=SURFACE2, spaceAfter=8))
    
    chart_idx = 0
    
    for i, qa in enumerate(qa_history, 1):
        question = qa.get("question", "")
        insight = qa.get("insight", {})
        code_info = qa.get("code_info", {})
        
        items = []
        
        # Question header
        items.append(Paragraph(f"Analysis {i}", styles["subsection"]))
        items.append(Paragraph(f"Question: {question}", styles["body"]))
        
        # Code/methodology
        if code_info.get("code"):
            items.append(Spacer(1, 4))
            items.append(Paragraph("Query / Code:", styles["muted"]))
            code_text = code_info["code"][:500]  # Truncate long code
            items.append(Paragraph(code_text.replace("\n", "<br/>"), styles["code"]))
        
        # Chart image
        if chart_idx < len(chart_images) and chart_images[chart_idx]:
            try:
                img_buf = io.BytesIO(chart_images[chart_idx])
                img = Image(img_buf, width=5.5 * inch, height=2.8 * inch)
                items.append(Spacer(1, 8))
                items.append(img)
                chart_idx += 1
            except Exception:
                chart_idx += 1
        
        # Insights
        if insight:
            items.append(Spacer(1, 8))
            items.append(Paragraph("Key Findings:", styles["muted"]))
            for finding in insight.get("key_findings", []):
                items.append(Paragraph(f"• {finding}", styles["finding"]))
            
            if insight.get("recommendation"):
                items.append(Spacer(1, 4))
                items.append(Paragraph(
                    f"💡 Recommendation: {insight['recommendation']}",
                    styles["body"]
                ))
        
        items.append(HRFlowable(width="100%", thickness=0.3, color=SURFACE2, spaceAfter=12))
        story.append(KeepTogether(items))
    
    return story